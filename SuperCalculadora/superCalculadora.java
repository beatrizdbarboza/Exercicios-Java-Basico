        int resto = valor % 2;
        lblResto.setText(Integer.toString(resto));
        System.out.println(resto);
        
        int exp = Integer.parseInt(lblValor.getValue().toString());
        int cubo = (int) Math.pow(exp, 2);
        lblCubo.setText(Double.toString(cubo));
        System.out.println(cubo);
        
        int r = Integer.parseInt(lblValor.getValue().toString());
