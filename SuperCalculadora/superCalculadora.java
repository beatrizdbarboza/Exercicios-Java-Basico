        lblCubica.setText(Double.toString(cubica));
        System.out.println(cubica);
        
        int abs = Integer.parseInt(lblValor.getValue().toString());
        int valorabs = (int) Math.abs(abs);
        lblAbsoluto.setText(Double.toString(valorabs));
